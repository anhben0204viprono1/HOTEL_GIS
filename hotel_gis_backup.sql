    count(DISTINCT r.id) FILTER (WHERE (r.status = 'available'::public.room_status)) AS available_rooms,
    min(rt.price_per_night) AS min_price,
    max(rt.price_per_night) AS max_price,
    (COALESCE(avg(rv.rating), (0)::numeric))::numeric(3,1) AS avg_rating,
    count(DISTINCT rv.id) AS review_count
   FROM (((public.hotels_hotel h
     LEFT JOIN public.hotels_roomtype rt ON ((rt.hotel_id = h.id)))
     LEFT JOIN public.hotels_room r ON ((r.hotel_id = h.id)))
     LEFT JOIN public.bookings_review rv ON (((rv.hotel_id = h.id) AND (rv.is_visible = true))))
  WHERE (h.is_active = true)
  GROUP BY h.id, h.name, h.city, h.star_rating, h.latitude, h.longitude;


