--
-- Name: v_booking_stats; Type: VIEW; Schema: public; Owner: postgres
--

CREATE VIEW public.v_booking_stats AS
 SELECT date_trunc('month'::text, b.created_at) AS month,
    count(*) AS total_bookings,
    count(*) FILTER (WHERE (b.status = 'cancelled'::public.booking_status)) AS cancelled,
    sum(b.total_price) AS gross_revenue,
    sum(p.amount) FILTER (WHERE (p.status = 'paid'::public.payment_status)) AS net_revenue
   FROM (public.bookings_booking b
     LEFT JOIN public.bookings_payment p ON ((p.booking_id = b.id)))
  GROUP BY (date_trunc('month'::text, b.created_at))
  ORDER BY (date_trunc('month'::text, b.created_at)) DESC;


